import React, { useState } from 'react';

const FUNGI_RE = /(mushroom|fung|toadstool|amanita|bolete|chanterelle|morel|agaric|russula|lactarius|cortinarius|polypore|puffball|mycena|psilocybe|galerina|lepiota|coprinus|pleurotus|bracket)/i;

/** True when a post looks like it shows a fungus (drives the foraging safety warning). */
export const isFungiPost = (post: { labels?: string[]; tags?: string[]; aiInsight?: string | null } | null | undefined) =>
  !!post && (
    (post.labels || []).some(l => FUNGI_RE.test(l)) ||
    (post.tags || []).some(t => FUNGI_RE.test(t))
  );

const CONF_COPY: Record<string, { label: string; tone: string }> = {
  high: { label: 'High confidence', tone: 'bg-emerald-50 text-emerald-800 border-emerald-200' },
  medium: { label: 'Medium confidence', tone: 'bg-amber-50 text-amber-900 border-amber-200' },
  low: { label: 'Low confidence', tone: 'bg-stone-100 text-stone-700 border-stone-300' },
};

/**
 * Transparent labelling for AI output (governance requirement):
 * every identification shown in the product is marked as an AI suggestion,
 * with its stated confidence and whether a person confirmed or corrected it.
 */
const AiBadge: React.FC<{ confidence?: string | null; humanVerified?: boolean; compact?: boolean }> = ({ confidence, humanVerified, compact }) => {
  const [open, setOpen] = useState(false);
  const conf = confidence ? CONF_COPY[confidence] : null;
  return (
    <div className="flex flex-wrap items-center gap-1.5">
      {humanVerified ? (
        <span className="inline-flex items-center gap-1 text-xs font-semibold px-2.5 py-1 rounded-full border bg-sky-50 text-sky-900 border-sky-200">
          <span className="material-symbols-outlined text-sm" aria-hidden="true">how_to_reg</span>
          Checked by explorer
        </span>
      ) : null}
      <button
        type="button"
        onClick={(e) => { e.stopPropagation(); setOpen(o => !o); }}
        aria-expanded={open}
        className="inline-flex items-center gap-1 text-xs font-semibold px-2.5 py-1 rounded-full border bg-white text-stone-700 border-stone-200 hover:bg-stone-50"
      >
        <span className="material-symbols-outlined text-sm" aria-hidden="true">auto_awesome</span>
        AI suggestion
        <span className="material-symbols-outlined text-sm" aria-hidden="true">info</span>
      </button>
      {conf && !compact && (
        <span className={`inline-flex items-center text-xs font-semibold px-2.5 py-1 rounded-full border ${conf.tone}`}>{conf.label}</span>
      )}
      {open && (
        <p className="basis-full text-xs text-stone-600 leading-relaxed bg-stone-50 rounded-xl p-3 mt-1">
          This identification and insight were generated by AI from the photo, video or sound. AI can be wrong, especially with partial views,
          look-alike species or poor light. {humanVerified ? 'The explorer reviewed it before posting. ' : ''}
          Treat it as a starting point and verify with field guides or local experts.
        </p>
      )}
    </div>
  );
};

export const FungiWarning: React.FC = () => (
  <div role="note" className="flex gap-3 p-3 rounded-xl bg-red-50 border border-red-200 text-red-900">
    <span className="material-symbols-outlined shrink-0" aria-hidden="true">warning</span>
    <p className="text-sm leading-snug"><strong>Never eat or handle wild fungi based on this ID.</strong> Many deadly mushrooms look like edible ones. Only a qualified local expert examining the specimen can confirm edibility.</p>
  </div>
);

export default AiBadge;
